#!/usr/bin/env python3
"""Embed the item icons into src/icons_data.h (ASCII C strings): Material Icon Theme SVGs from
third_party/material-icons plus our own from tools/icons. Run from the repo root."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..")
# canonical name -> source folder ("m" Material, "o" ours)
ICONS = [("key", "m"), ("lock", "m"), ("http", "m"), ("console", "m"), ("git", "m"), ("docker", "m"),
         ("vscode", "m"), ("database", "m"), ("certificate", "m"), ("android", "m"), ("nodejs", "m"),
         ("python", "m"), ("folder-secure", "m"), ("keyring", "o"), ("wifi", "o"), ("mail", "o"), ("app", "o"),
         ("browser", "o")]

def load(path):
    svg = open(path, encoding="utf-8").read()
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r"<\?xml.*?\?>", "", svg, flags=re.S)
    svg = re.sub(r"\s+", " ", svg).strip()
    svg.encode("ascii")  # must be ASCII
    return svg

def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["// icons_data.h - GENERATED by tools/gen_icons.py, do not edit", ""]
out.append("enum {")
for name, _ in ICONS:
    out.append(f"    ICON_{name.upper().replace('-', '_')},")
out.append("    ICON_COUNT")
out.append("};")
out.append("")
out.append("static const char *const g_icon_names[ICON_COUNT] = {")
out.append("    " + ", ".join(c_string(n) for n, _ in ICONS) + ",")
out.append("};")
out.append("")
out.append("static const char *const g_icon_svg[ICON_COUNT] = {")
for name, src in ICONS:
    d = os.path.join(root, "third_party", "material-icons") if src == "m" else os.path.join(here, "icons")
    out.append("    " + c_string(load(os.path.join(d, name + ".svg"))) + ",")
out.append("};")
open(os.path.join(root, "src", "icons_data.h"), "w").write("\n".join(out) + "\n")
print(f"wrote src/icons_data.h ({len(ICONS)} icons)")
